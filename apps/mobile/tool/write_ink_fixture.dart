// PURPOSE: Write the iReal export an automated browser run loads into the application, so that a
//          headless verification draws on a chart whose layout it also knows. The notation is
//          written with the package's OWN encoder rather than transcribed by hand, which is what
//          keeps the fixture from drifting from the reader: a hand-built payload would agree with a
//          hand-built understanding of the format and with nothing else.
// INPUTS: argv[0] — the directory to write into.
// OUTPUTS: `<dir>/ink-fixture.html`, an iReal Pro export page carrying one `irealb://` link for a
//          twelve-bar two-section song, plus the notation it encodes on stdout so a run can compare
//          what it expected against what it drew. Exits 1 when no directory was given.
// KEYWORDS: fixture, ireal-export, encoder-round-trip, browser-verification, diagnostic
//
// NOT PART OF THE PRODUCT. A diagnostic harness for a verification run, in the same class as
// `tool/probe_ireal.dart`, and it writes outside the repository.
import 'dart:io';

import 'package:chart_core/chart_core.dart';
import 'package:chartapp/ireal_library.dart';

/// The short iReal notation the fixture encodes when a run asks for it: two sections of six bars.
///
/// It fits on one page at scale 1 on a desktop pane, which is the case in which aiming at a cell is
/// simplest, and it is the one used for the drawing and undo screenshots.
const String fixtureNotationShort =
    '*AT44C^7 |C^7 F^7 |C^7 |G-7 C7 |F^7 |F^7 |'
    '*BT44C^7 |C^7 F^7 |C^7 |G-7 C7 |F^7 |C^7 Z';

/// The long iReal notation the fixture encodes by default: four sections of sixteen bars.
///
/// It is deliberately long enough that FIT has to shrink it on a desktop pane — a chart that already
/// fits at scale 1 makes a fitted page indistinguishable from an ordinary one, and exercising the
/// page transform is the whole point of the fixture. `C^7` opens every bar and every even bar carries
/// a second chord on its third beat, so a bar has an interior feature a stroke can be aimed at.
const String fixtureNotationLong =
    '*AT44'
    'C^7 |C^7 F^7 |C^7 |G-7 C7 |F^7 |F^7 |C^7 |C^7 F^7 |'
    'C^7 |G-7 C7 |F^7 |F^7 |C^7 |C^7 F^7 |C^7 |G-7 C7 |'
    '*BT44'
    'C^7 |C^7 F^7 |C^7 |G-7 C7 |F^7 |F^7 |C^7 |C^7 F^7 |'
    'C^7 |G-7 C7 |F^7 |F^7 |C^7 |C^7 F^7 |C^7 |G-7 C7 |'
    '*CT44'
    'C^7 |C^7 F^7 |C^7 |G-7 C7 |F^7 |F^7 |C^7 |C^7 F^7 |'
    'C^7 |G-7 C7 |F^7 |F^7 |C^7 |C^7 F^7 |C^7 |G-7 C7 |'
    '*DT44'
    'C^7 |C^7 F^7 |C^7 |G-7 C7 |F^7 |F^7 |C^7 |C^7 F^7 |'
    'C^7 |G-7 C7 |F^7 |F^7 |C^7 |C^7 F^7 |C^7 Z';

/// The title the fixture's song carries, so a run can name the chart it loaded.
const String fixtureTitle = 'Ink verification';

void main(List<String> args) {
  if (args.isEmpty) {
    stderr.writeln('usage: ink_fixture <output-directory> [short|long]');
    exit(1);
  }
  final bool short = args.length > 1 && args[1] == 'short';
  final String fixtureNotation = short
      ? fixtureNotationShort
      : fixtureNotationLong;
  final String fileName = short ? 'ink-fixture-short.html' : 'ink-fixture.html';
  final String music =
      '$irealMusicPrefix${obfuscateIrealMusic(fixtureNotation)}';
  final String payload =
      '$fixtureTitle=ChartApp==Medium Swing=C=0=$music=Medium Swing=120=1';
  final String link = Uri.encodeComponent(payload);
  final String html =
      '''
<!DOCTYPE html>
<html lang="en">
<!--
  PURPOSE: Stand in for an iReal Pro export so an automated browser run can load a known chart
           through the application's real file-chooser path rather than through a test-only seam.
  NOT PART OF THE PRODUCT. Generated by apps/mobile/tool/write_ink_fixture.dart.
-->
<head><meta charset="utf-8"><title>$fixtureTitle</title></head>
<body>
<a href="irealb://$link">$fixtureTitle</a>
</body>
</html>
''';
  final String directory = args[0];
  final File out = File('$directory${Platform.pathSeparator}$fileName')
    ..parent.createSync(recursive: true);
  out.writeAsStringSync(html);
  stdout.writeln(
    'ink_fixture.wrote path=${out.path} bytes=${out.lengthSync()}',
  );
  stdout.writeln('ink_fixture.notation $fixtureNotation');
  final IRealLibrary library = parseIRealLibrary(payload);
  final Song song = library.songs.single.song;
  stdout.writeln(
    'ink_fixture.parsed title="${song.title}" key=${song.key} '
    'bars=${song.writtenBarCount} sections=${song.sections.length}',
  );
  for (final Section section in song.sections) {
    stdout.writeln(
      'ink_fixture.section id=${section.id} bars=${section.bars.length}',
    );
  }
}
